//! 変換: 読み取った交信(`QsoRecord`)から、SOTA の CSV・ADIF の出力ファイルを作る
//!
//! - `sota`: SOTA アクティベーター(CSV・S2S の CSV・ADIF)、SOTA チェイサー(CSV)
//! - `adif`: 自局の参照ごとの ADIF(POTA・WWFF・SOTA)と、確認画面に出す表
//! - `refs`: 備考・QTH の列から、自局・相手の参照を取る
//! - `files`: 出力ファイルの集まり、CSV の書式、ZIP
//!
//! 旧版(HamLogConv の Python)と同じ出力にする(`test_data/logconv/legacy` が、旧版の出力の正解)。
//!
//! ## 旧版に合わせた癖(理由を知らないと分かりにくいもの)
//!
//! - **ADIF のファイル名の日付**: 山(`/` を含む参照)は、その交信の日付のファイル。公園と WWFF は、最初の交信の日付の
//!   1つのファイル。(POTA は1回の運用を1つのファイルにして出すため。山は日ごとにアクティベーションを数えるため)
//! - **SOTA の CSV の最後の列(場所の注記)**: アクティベーターは、相手の参照に付いた座標(`%QTH%35.6N, 139.2E%`)。
//!   チェイサーは、相手の参照を置いていない側の備考の場所。どちらも、相手を指定しないときは空白。末尾に空白が1つ付く。
//! - **SOTA アクティベーターの ADIF**: 項目は空白で区切り、`ADIF_VER` は `3.0.6`(POTA・WWFF は `3.1.4`)。
//! - **空の RST**: 項目は省かず `<RST_SENT:0>` と出す。
//! - **時刻の `U` / `Z` / `J`**: `U` と `Z` は UTC。それ以外(`J` や、付かないとき)は JST(HAMLOG は常に付けるが、旧版も JST 扱い)。
//! - **2桁の年**: 65 以上は 19xx、未満は 20xx。
//! - **公園の所在地(`MY_STATE`)**: 所在地が1つに決まる公園だけ入れる。
//!
//! ## 旧版と違う所(直したもの)
//!
//! - 日付が前後するログや、誤りの行が間にあるログで、交信が消えていた(旧版は同じ日付のファイルを上書きしていた)。
//! - 読み取りに失敗した行は、ADIF に入れない(旧版は、エラー文つきの壊れた記録を入れていた)。`status: NG` と
//!   行番号で知らせる。CSV では `sota000000.csv` に集める(日付のファイルは、そのままアップロードするため)。
//! - チェイサーは、日付ごとにファイルを分ける(旧版は、全日付を最初の日付の名前の1ファイルにしていた)。
//! - SOTA アクティベーターで、相手の山を QTH の列から読める(旧版の画面は、備考1・備考2だけだった)。FLE の
//!   HAMLOG の CSV は、相手の参照を QTH の列に書くので、S2S が落ちていた。

